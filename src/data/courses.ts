function titleFor(uci: string) {
  if (uci === 'e1g1' || uci === 'e8g8') return 'Сховай короля'
  if (['g1f3','b1c3','g8f6','b8c6','f1c4','f1b5','f8b4','f8c5','c1f4','c1g5','c8f5','c8g4','f1e2','f8e7','f8g7'].includes(uci)) return 'Розвивай фігуру'
  if (uci.includes('d4') || uci.includes('e4') || uci.includes('d5') || uci.includes('e5')) return 'Борись за центр'
  return 'Продовжуй план варіанта'
}

function explanation(line: RepertoireLine, index: number, move: Move) {
  if (line.ideas?.[index]) return line.ideas[index]
  if (line.moves[index] === 'c5d4' && move.piece === 'b') return 'Слон бере фігуру на d4 і відкриває центральну діагональ.'
  if (line.moves[index] === 'c5b4') return move.captured ? 'Слон бере пішака на b4.' : 'Слон виходить на b4 із шахом.'
  if (line.moves[index] === 'd1f3' && move.captured) return 'Ферзь відновлює фігуру на f3.'
  if (moveIdeas[line.moves[index]]) return moveIdeas[line.moves[index]]
  const pieces: Record<Move['piece'], string> = { p: 'Пішак', n: 'Кінь', b: 'Слон', r: 'Тура', q: 'Ферзь', k: 'Король' }
  return `${pieces[move.piece]} ${move.captured ? 'бере фігуру на' : 'переходить на'} ${move.to}${/[+#]$/.test(move.san) ? ' з шахом' : ''}.`
}

function scenarios(lines: RepertoireLine[], color: 'white' | 'black'): CourseScenario[] {
  return lines.map((line) => {
    const game = new Chess()
    const notes = line.moves.map((uci, index) => {
      const move = game.move({ from: uci.slice(0, 2), to: uci.slice(2, 4), promotion: uci[4] || 'q' })
      if (!move) throw new Error(`Нелегальний хід ${uci} у ${line.id}`)
      return explanation(line, index, move)
    })
    const steps: CourseStep[] = []
    const start = color === 'white' ? 0 : 1
    for (let index = start; index + 1 < line.moves.length; index += 2) {
      steps.push({
        userMove: line.moves[index],
        title: titleFor(line.moves[index]),
        explanation: notes[index],
        opponentMove: line.moves[index + 1],
        opponentExplanation: notes[index + 1],
      })
    }
    return {
      id: `${color}-${line.id}`,
      name: line.name,
      initialMove: color === 'black' ? line.moves[0] : undefined,
      initialExplanation: color === 'black' ? notes[0] : undefined,
      steps,
    }
  })
}

